import type { PaletteId } from "../lib/types";

/**
 * Color palettes for the Appearance setting (wiki app-config.md,
 * `appearance.palette`). Each palette overrides the CSS custom properties
 * declared in `styles/tokens.css`; `default` overrides nothing, so the
 * tokens file stays the single source of the stock look.
 *
 * Contrast is checked in `styles/__tests__/palettes.test.ts`: primary text
 * and accent meet WCAG AA (4.5:1) against every surface they sit on.
 */

/** Every token a palette may override (all colors in tokens.css). */
export const PALETTE_TOKENS = [
  "--color-bg-app",
  "--color-bg-activitybar",
  "--color-bg-listpanel",
  "--color-bg-editor",
  "--color-bg-statusbar",
  "--color-border",
  "--color-border-strong",
  "--color-text-primary",
  "--color-text-secondary",
  "--color-text-muted",
  "--color-text-inverse",
  "--color-accent",
  "--color-accent-hover",
  "--color-selection",
  "--color-activitybar-icon",
  "--color-activitybar-icon-active",
  "--color-activitybar-active-bar",
  "--color-hover",
  "--color-active",
  "--color-danger",
  "--color-warning",
  "--color-success",
] as const;

export type PaletteToken = (typeof PALETTE_TOKENS)[number];

export interface Palette {
  id: PaletteId;
  label: string;
  /** One-line description for the picker's accessible name / tooltip. */
  description: string;
  scheme: "light" | "dark";
  /** Picker preview: [surface, side panel, accent, text]. */
  swatches: readonly [string, string, string, string];
  /** Token overrides; empty for `default`. */
  vars: Partial<Record<PaletteToken, string>>;
}

